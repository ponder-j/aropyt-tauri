export type LabelKey = keyof typeof L;

export function pick(lang: Lang, key: LabelKey): string {
  const pair = L[key];
  return lang === 'zh' ? pair[0] : pair[1];
}

/** Resolves the effective language from an OS locale and a user preference. */
export function resolveLang(locale: string, pref: LangPref | string | undefined): Lang {
  if (pref === 'zh' || pref === 'en') return pref;
  return locale.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

