import { spawn } from 'node:child_process';
import path from 'node:path';
import os from 'node:os';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const env = { ...process.env, PATH: path.join(process.env.CARGO_HOME || path.join(os.homedir(), '.cargo'), 'bin') + path.delimiter + process.env.PATH };
const command = require.resolve('@tauri-apps/cli/tauri.js');
const child = spawn(process.execPath, [command, ...process.argv.slice(2)], { stdio: 'inherit', env });
child.on('error', error => { console.error(error); process.exitCode = 1; });
child.on('exit', code => { process.exitCode = code ?? 1; });
